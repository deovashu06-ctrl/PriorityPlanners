from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import landscape, A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from sqlalchemy.orm import Session
import models

DAY_ORDER = {"Monday": 0, "Tuesday": 1, "Wednesday": 2, "Thursday": 3, "Friday": 4}


def build_timetable_pdf(db: Session, batch_id: int | None = None):
    batches = db.query(models.Batch).all()
    if batch_id is not None:
        batches = [b for b in batches if b.id == batch_id]

    slots = sorted(db.query(models.TimeSlot).all(), key=lambda s: (DAY_ORDER.get(s.day, 99), s.start_time))
    days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]
    periods = []
    seen = set()
    for s in slots:
        if s.start_time not in seen:
            periods.append((s.start_time, s.end_time))
            seen.add(s.start_time)

    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), rightMargin=24, leftMargin=24, topMargin=22, bottomMargin=22)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("TitleX", parent=styles["Title"], fontSize=20, alignment=TA_CENTER, spaceAfter=10)
    cell = ParagraphStyle("CellX", parent=styles["BodyText"], fontSize=7.5, leading=9, alignment=TA_CENTER)
    story = []

    for idx, batch in enumerate(batches):
        story.append(Paragraph(f"PriorityPlanners — Timetable · {batch.name}", title))
        data = [[Paragraph("Time", cell)] + [Paragraph(d[:3], cell) for d in days]]
        for start, end in periods:
            row = [Paragraph(f"{start}<br/>{end}", cell)]
            for day in days:
                slot = next((s for s in slots if s.day == day and s.start_time == start), None)
                entries = []
                if slot:
                    entries = db.query(models.TimetableEntry).filter(
                        models.TimetableEntry.batch_id == batch.id,
                        models.TimetableEntry.time_slot_id == slot.id,
                    ).all()
                if not entries:
                    row.append(Paragraph("—", cell))
                    continue
                bits = []
                for e in entries:
                    subj = db.query(models.Subject).filter(models.Subject.id == e.subject_id).first()
                    fac = db.query(models.Faculty).filter(models.Faculty.id == e.faculty_id).first()
                    room = db.query(models.Room).filter(models.Room.id == e.room_id).first()
                    bits.append(f"<b>{subj.name if subj else 'Class'}</b><br/>{fac.name if fac else ''}<br/>{room.room_number if room else ''}")
                row.append(Paragraph("<hr/>".join(bits), cell))
            data.append(row)

        table = Table(data, colWidths=[58] + [138] * 5, repeatRows=1)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#111111")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#B7B7B7")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(table)
        story.append(Spacer(1, 10))
        story.append(Paragraph("Generated by PriorityPlanners", styles["Normal"]))
        if idx != len(batches) - 1:
            story.append(PageBreak())

    doc.build(story)
    buf.seek(0)
    return buf.getvalue()
